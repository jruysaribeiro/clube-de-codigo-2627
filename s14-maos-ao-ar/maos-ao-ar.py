def classificar_mao(pontos, proporcao):
    # pontos: 21 pares (x, y) de 0 a 1. proporcao: largura / altura da imagem.
    # Um dedo esta esticado se a ponta estiver mais longe do pulso do que a
    # articulacao do meio. Funciona com a mao em qualquer posicao.
    pulso = pontos[0]

    def distancia(indice):
        dx = (pontos[indice][0] - pulso[0]) * proporcao
        dy = pontos[indice][1] - pulso[1]
        return math.hypot(dx, dy)

    indicador = distancia(8) > distancia(6) * 1.12
    medio = distancia(12) > distancia(10) * 1.12
    anelar = distancia(16) > distancia(14) * 1.12
    mindinho = distancia(20) > distancia(18) * 1.12
    quantos = 0
    for esticado in (indicador, medio, anelar, mindinho):
        if esticado:
            quantos += 1

    if quantos == 0:
        return "punho"
    if quantos == 1 and indicador:
        return "apontar"
    if quantos >= 3:
        return "aberta"
    return "outra"          # a meio caminho: nao se muda nada


def centro_da_palma(pontos):
    x = 0.0
    y = 0.0
    for indice in (0, 5, 9, 13, 17):
        x += pontos[indice][0]
        y += pontos[indice][1]
    return x / 5, y / 5


def ciclo_da_camara():
    # Corre no fio da camara ate `mao["ligada"]` passar a False.
    captura = camara["captura"]
    detetor = camara["detetor"]
    forma_crua_anterior = "nenhuma"
    repetidas = 0
    ultima_vez = 0.0
    ultimo_ms = 0
    falhas = 0
    try:
        while mao["ligada"]:
            ok, imagem = captura.read()
            if not ok or imagem is None:
                falhas += 1
                if falhas > 60:
                    mao["erro"] = "A câmara deixou de responder."
                    break
                time.sleep(0.02)
                continue
            falhas = 0

            # Espelho (para a tua direita ser a direita do ecra), e mais
            # pequena, que chega e e mais rapido.
            imagem = cv2.flip(imagem, 1)
            altura = int(imagem.shape[0] * 480 / imagem.shape[1])
            imagem = cv2.resize(imagem, (480, altura))
            rgb = numpy.ascontiguousarray(cv2.cvtColor(imagem, cv2.COLOR_BGR2RGB))

            agora_ms = int(time.monotonic() * 1000)
            if agora_ms <= ultimo_ms:
                agora_ms = ultimo_ms + 1
            ultimo_ms = agora_ms
            imagem_mp = mediapipe.Image(image_format=mediapipe.ImageFormat.SRGB, data=rgb)
            resultado = detetor.detect_for_video(imagem_mp, agora_ms)

            pontos = []
            if len(resultado.hand_landmarks) > 0:
                for ponto in resultado.hand_landmarks[0]:
                    pontos.append((ponto.x, ponto.y))

            agora = time.monotonic()
            tranca.acquire()
            if len(pontos) == 21:
                ultima_vez = agora
                x, y = centro_da_palma(pontos)
                if mao["visivel"]:
                    # media com a posicao anterior, para nao tremer
                    mao["x"] = mao["x"] * 0.5 + x * 0.5
                    mao["y"] = mao["y"] * 0.5 + y * 0.5
                else:
                    mao["x"] = x
                    mao["y"] = y
                mao["visivel"] = True

                # Uma forma so conta quando aparece em 2 imagens seguidas.
                forma_crua = classificar_mao(pontos, 480 / altura)
                if forma_crua == forma_crua_anterior:
                    repetidas += 1
                else:
                    repetidas = 1
                forma_crua_anterior = forma_crua
                if repetidas >= 2 and forma_crua != "outra" and forma_crua != mao["forma"]:
                    if forma_crua == "punho":
                        mao["saltos"] += 1
                    mao["forma"] = forma_crua
            elif agora - ultima_vez > TEMPO_SEM_MAO:
                mao["visivel"] = False
                mao["forma"] = "nenhuma"
                forma_crua_anterior = "nenhuma"
            mao["pontos"] = pontos
            mao["imagem"] = rgb.tobytes()
            mao["tamanho"] = (480, altura)
            mao["numero"] += 1
            tranca.release()
    except Exception as erro:
        mao["erro"] = "Erro na câmara: " + str(erro)
        if tranca.locked():
            tranca.release()
    mao["ligada"] = False
    mao["visivel"] = False


def ligar_camara(indice, espera_no_mac):
    # Tem de ser chamada no fio principal: no Mac, e ai que o sistema
    # pergunta se o Terminal pode usar a camara.
    desligar_camara()
    mao["indice"] = indice
    mao["erro"] = ""
    if not HA_BIBLIOTECAS_DA_CAMARA:
        mao["erro"] = "Falta o mediapipe ou o opencv."
        return False
    modelo = obter_modelo()
    if modelo is None:
        mao["erro"] = "Falta o modelo das mãos (sem internet?)."
        return False
    guardado = calar_avisos()
    try:
        # No Mac, a primeira vez, o sistema pergunta se o Terminal pode usar
        # a camara, e enquanto a pergunta esta no ecra a camara nao abre.
        # Por isso tenta-se varias vezes, para dar tempo de responder.
        tentativas = 1
        if sys.platform == "darwin" and espera_no_mac:
            tentativas = 12
        captura = None
        for tentativa in range(tentativas):
            if os.name == "nt":
                captura = cv2.VideoCapture(indice, cv2.CAP_DSHOW)   # abre mais depressa
            else:
                captura = cv2.VideoCapture(indice)
            if captura.isOpened():
                break
            captura.release()
            captura = None
            if tentativa + 1 < tentativas:
                pygame.event.pump()
                time.sleep(1.0)
        if captura is None:
            repor_avisos(guardado)
            mao["erro"] = "Não há câmara " + str(indice) + " (ou não há permissão)."
            return False
        captura.set(cv2.CAP_PROP_FRAME_WIDTH, 640)
        captura.set(cv2.CAP_PROP_FRAME_HEIGHT, 480)
        captura.set(cv2.CAP_PROP_BUFFERSIZE, 1)

        # Ler o modelo para a memoria em vez de dar o caminho: no Windows,
        # um caminho com acentos (C:\Users\João) baralha o mediapipe.
        ficheiro = open(modelo, "rb")
        dados = ficheiro.read()
        ficheiro.close()
        opcoes = mp_visao.HandLandmarkerOptions(
            base_options=mp_tarefas.BaseOptions(model_asset_buffer=dados),
            running_mode=mp_visao.RunningMode.VIDEO,
            num_hands=1,
            min_hand_detection_confidence=0.5,
            min_hand_presence_confidence=0.5,
            min_tracking_confidence=0.5,
        )
        detetor = mp_visao.HandLandmarker.create_from_options(opcoes)
        # Uma imagem preta so para aquecer: a primeira e sempre a mais lenta.
        preta = mediapipe.Image(image_format=mediapipe.ImageFormat.SRGB,
                                data=numpy.zeros((360, 480, 3), numpy.uint8))
        detetor.detect_for_video(preta, 0)
    except Exception as erro:
        repor_avisos(guardado)
        mao["erro"] = "A câmara não arrancou: " + str(erro)
        return False
    repor_avisos(guardado)

    camara["captura"] = captura
    camara["detetor"] = detetor
    mao["ligada"] = True
    mao["numero"] = 0
    camara["fio"] = threading.Thread(target=ciclo_da_camara, daemon=True)
    camara["fio"].start()
    return True



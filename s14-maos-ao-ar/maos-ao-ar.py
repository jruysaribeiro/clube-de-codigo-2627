        confirmou = False       # o mesmo, mais o Enter
        fase = jogo["fase"]

        for evento in pygame.event.get():
            if evento.type == pygame.QUIT:
                a_correr = False
            elif evento.type == pygame.KEYDOWN:
                tecla = evento.key
                if tecla == pygame.K_ESCAPE:
                    if fase == "titulo":
                        a_correr = False
                    else:
                        jogo["fase"] = "titulo"

def descarregar(url, destino):
    # Descarrega para um ficheiro ao lado e so no fim lhe da o nome certo:
    # assim nunca fica um modelo cortado a meio com o nome verdadeiro.
    temporario = destino + ".parte"
    try:
        contexto = ssl.create_default_context()
        try:
            # O Python do python.org no Mac nao traz certificados; o certifi
            # (que vem com o mediapipe) resolve.
            import certifi
            contexto = ssl.create_default_context(cafile=certifi.where())
        except Exception:
            pass
        resposta = urllib.request.urlopen(url, timeout=30, context=contexto)
        dados = resposta.read()
        resposta.close()
        ficheiro = open(temporario, "wb")
        ficheiro.write(dados)
        ficheiro.close()
    except Exception:
        # Plano B: o curl, que existe no Mac, no Linux e no Windows 10+.
        try:
            subprocess.call(["curl", "-L", "--fail", "-s", "-o", temporario, url])
        except OSError:
            pass
    try:
        if os.path.getsize(temporario) >= MODELO_TAMANHO_MINIMO:
            os.replace(temporario, destino)
            return True
        os.remove(temporario)
    except OSError:
        pass
    return False



def bate_em_solido(x, y, largura, altura):
    coluna_0 = int(math.floor(x / TILE))
    coluna_1 = int(math.ceil((x + largura) / TILE)) - 1
    linha_0 = int(math.floor(y / TILE))
    linha_1 = int(math.ceil((y + altura) / TILE)) - 1
    for linha in range(linha_0, linha_1 + 1):
        for coluna in range(coluna_0, coluna_1 + 1):
            if e_solido(coluna, linha):
                return True
    return False


def mover_corpo(corpo, dx, dy):
    # Move um corpo (o heroi ou um inimigo) e para-o nas paredes e no chao.
    # Primeiro para os lados, depois para cima/baixo: e o truque de sempre.
    # Devolve True se bateu numa parede.
    largura = corpo["l"]
    altura = corpo["a"]
    bateu = False

    corpo["x"] += dx
    if bate_em_solido(corpo["x"], corpo["y"], largura, altura):
        if dx > 0:
            coluna = int(math.ceil((corpo["x"] + largura) / TILE)) - 1
            corpo["x"] = coluna * TILE - largura
        elif dx < 0:
            coluna = int(math.floor(corpo["x"] / TILE))
            corpo["x"] = (coluna + 1) * TILE
        bateu = True

    pes_antes = corpo["y"] + altura
    corpo["y"] += dy
    corpo["no_chao"] = False
    if bate_em_solido(corpo["x"], corpo["y"], largura, altura):
        if dy > 0:
            linha = int(math.ceil((corpo["y"] + altura) / TILE)) - 1
            corpo["y"] = linha * TILE - altura
            corpo["no_chao"] = True
        elif dy < 0:
            linha = int(math.floor(corpo["y"] / TILE))
            corpo["y"] = (linha + 1) * TILE
        corpo["vy"] = 0.0
    elif dy >= 0:
        # Plataformas "=": so seguram quem vem de cima.
        pes = corpo["y"] + altura
        linha = int(math.floor(pes / TILE))
        topo = linha * TILE
        if pes_antes <= topo + 0.01:
            coluna_0 = int(math.floor(corpo["x"] / TILE))
            coluna_1 = int(math.ceil((corpo["x"] + largura) / TILE)) - 1
            for coluna in range(coluna_0, coluna_1 + 1):
                if letra_em(coluna, linha) == "=":
                    corpo["y"] = topo - altura
                    corpo["vy"] = 0.0
                    corpo["no_chao"] = True
                    break
    return bateu


def retangulo(corpo):
    return pygame.Rect(int(corpo["x"]), int(corpo["y"]), corpo["l"], corpo["a"])


def particulas(x, y, cor, quantas, forca):
    for i in range(quantas):
        angulo = random.uniform(0, math.tau)
        velocidade = random.uniform(0.3, 1.0) * forca
        nivel["particulas"].append({
            "x": x, "y": y,
            "vx": math.cos(angulo) * velocidade,
            "vy": math.sin(angulo) * velocidade - forca * 0.3,
            "vida": random.randint(18, 36), "cor": cor,
            "tamanho": random.randint(3, 6),
        })



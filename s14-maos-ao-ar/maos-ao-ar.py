# =====================================================================
# S14 — MAOS AO AR!
#
# Um jogo de plataformas que se joga SEM TOCAR NO COMPUTADOR: a camara ve
# a tua mao e o Faisca (o robot) faz o que ela mandar. Vinte niveis, cada
# um mais dificil do que o anterior, e um chefe a tua espera no ultimo.
# Antes deles ha o nivel 0, o recreio, para experimentar os gestos.
#
# O Faisca anda sozinho. Tu so decides para onde, e quando.
#
#                      COM A MAO                      NO TECLADO
#   andar              mostrar a mao a camara         (anda sozinho)
#   parar              tirar a mao da imagem          seta para baixo
#   virar              levar a mao para o outro lado  setas esquerda/direita
#   correr             levantar a mao bem alto        Shift
#   saltar             fechar o punho                 Espaco ou seta para cima
#   disparar           apontar com o indicador        X
#
#   pausa   P          janela / ecra inteiro   F ou F11        sair   Esc
#   T   jogar so com o teclado (o Faisca anda sem precisar da mao)
#   C   experimentar a camara seguinte (se o computador tiver mais do que uma)
#   I   voltar ao treino dos gestos
#
# A PRIMEIRA VEZ QUE CORRE, este ficheiro instala sozinho o que lhe falta
# (pygame-ce, mediapipe, opencv) e vai buscar o modelo que reconhece maos.
# Precisa de internet so dessa vez. Se o Python for o do sistema, pede a
# palavra-passe de administrador (sudo). Ver o NOTAS.md.

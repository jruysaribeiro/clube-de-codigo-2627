def desenhar_mapa(camara_x):
    primeira = int(camara_x // TILE)
    for linha in range(LINHAS):
        for coluna in range(primeira, primeira + LARGURA // TILE + 2):
            if coluna < 0 or coluna >= nivel["colunas"]:
                continue
            letra = nivel["grelha"][linha][coluna]
            if letra != ".":
                desenhar_quadrado(letra, coluna, linha,
                                  int(coluna * TILE - camara_x), linha * TILE)



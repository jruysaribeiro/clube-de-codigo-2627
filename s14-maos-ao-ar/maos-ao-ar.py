def calar_avisos():
    # O opencv e o mediapipe enchem o terminal de avisos em ingles que
    # assustam e nao querem dizer nada. Enquanto eles arrancam, manda-se a
    # saida de erros para o lixo. Devolve o que e preciso para a repor.
    try:
        sys.stderr.flush()
        guardado = os.dup(2)
        lixo = os.open(os.devnull, os.O_WRONLY)
        os.dup2(lixo, 2)
        os.close(lixo)
        return guardado
    except (OSError, ValueError):
        return None



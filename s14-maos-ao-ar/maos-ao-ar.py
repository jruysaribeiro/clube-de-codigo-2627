    # A imagem da camara, com as linhas das zonas e o esqueleto da mao.
    # Devolve a altura do que desenhou.
    ecra = janela["ecra"]
    if m["imagem"] is None or m["tamanho"][0] == 0:
        altura = largura * 3 // 4
        pygame.draw.rect(ecra, (30, 30, 48), (x, y, largura, altura), border_radius=6)
        escrever("sem câmara", "p", CINZA, x + largura // 2, y + altura // 2 - 10, "centro")
        return altura
    altura = largura * m["tamanho"][1] // m["tamanho"][0]
    if jogo.get("camara_numero") != (m["numero"], largura):
        imagem = pygame.image.frombuffer(m["imagem"], m["tamanho"], "RGB")
        jogo["camara_imagem"] = pygame.transform.scale(imagem, (largura, altura))
        jogo["camara_numero"] = (m["numero"], largura)
    ecra.blit(jogo["camara_imagem"], (x, y))

    # as zonas
    pygame.draw.line(ecra, BRANCO, (x + largura * ZONA_ESQUERDA, y), (x + largura * ZONA_ESQUERDA, y + altura), 1)
    pygame.draw.line(ecra, BRANCO, (x + largura * ZONA_DIREITA, y), (x + largura * ZONA_DIREITA, y + altura), 1)
    pygame.draw.line(ecra, AMARELO, (x, y + altura * LINHA_CORRER), (x + largura, y + altura * LINHA_CORRER), 2)

    # o esqueleto
    cor = VERDE
    if m["forma"] == "punho":
        cor = AZUL
    elif m["forma"] == "apontar":
        cor = VERMELHO
    grossura = max(2, largura // 120)
    if len(m["pontos"]) == 21:
        for a, b in LIGACOES_DA_MAO:
            pygame.draw.line(ecra, cor,
                             (x + m["pontos"][a][0] * largura, y + m["pontos"][a][1] * altura),
                             (x + m["pontos"][b][0] * largura, y + m["pontos"][b][1] * altura), grossura)
    if m["visivel"]:
        pygame.draw.circle(ecra, BRANCO, (int(x + m["x"] * largura), int(y + m["y"] * altura)),
                           grossura * 3)
        pygame.draw.circle(ecra, cor, (int(x + m["x"] * largura), int(y + m["y"] * altura)),
                           grossura * 3, 2)
    borda = CINZA
    if m["visivel"]:
        borda = cor
    pygame.draw.rect(ecra, borda, (x - 2, y - 2, largura + 4, altura + 4), 3, border_radius=4)
    return altura



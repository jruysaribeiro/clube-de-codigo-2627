def fazer_som(notas, volume, onda):
    # notas: lista de (frequencia inicial, frequencia final, segundos).
    taxa, formato, canais = pygame.mixer.get_init()
    dados = array.array("h")
    fase = 0.0
    for inicio, fim, duracao in notas:
        total = int(taxa * duracao)
        for i in range(total):
            parte = i / total
            fase += (inicio + (fim - inicio) * parte) / taxa
            if onda == "quadrada":
                valor = 1.0
                if fase % 1.0 > 0.5:
                    valor = -1.0
            elif onda == "ruido":
                valor = random.uniform(-1, 1)
            else:
                valor = math.sin(fase * math.tau)
            amostra = int(valor * volume * (1.0 - parte) * 32767)
            for canal in range(canais):
                dados.append(amostra)
    return pygame.mixer.Sound(buffer=dados)



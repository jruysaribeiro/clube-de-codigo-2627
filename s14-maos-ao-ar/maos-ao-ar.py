def atualizar_heroi(comando):
    if heroi["congelado"] > 0:
        heroi["congelado"] -= 1
        comando = {"direcao": comando["direcao"], "andar": False, "correr": False,
                   "saltar": False, "disparar": False}
    if heroi["invencivel"] > 0:
        heroi["invencivel"] -= 1

    if comando["direcao"] != 0:
        heroi["virado"] = comando["direcao"]

    velocidade = 0.0
    if comando["andar"]:
        velocidade = VEL_ANDAR
        if comando["correr"]:
            velocidade = VEL_CORRER
    heroi["vx"] = velocidade * heroi["virado"]

    # Saltar. Duas ajudas: o salto pedido um pouco antes de tocar no chao
    # ainda conta, e ainda se pode saltar um instante depois de cair da beira.
    if comando["saltar"]:
        heroi["salto_pedido"] = TOLERANCIA_SALTO
    if heroi["no_chao"]:
        heroi["coiote"] = TEMPO_COIOTE
    if heroi["salto_pedido"] > 0 and heroi["coiote"] > 0:
        heroi["vy"] = -FORCA_SALTO
        heroi["salto_pedido"] = 0
        heroi["coiote"] = 0
        tocar("salto")
        acao("SALTO!")
        particulas(heroi["x"] + 15, heroi["y"] + ALTURA_HEROI, BRANCO, 5, 2)
    if heroi["salto_pedido"] > 0:
        heroi["salto_pedido"] -= 1
    if heroi["coiote"] > 0:
        heroi["coiote"] -= 1

    heroi["vy"] += GRAVIDADE
    if heroi["vy"] > VEL_QUEDA_MAXIMA:
        heroi["vy"] = VEL_QUEDA_MAXIMA
    mover_corpo(heroi, heroi["vx"], heroi["vy"])
    heroi["passo"] += abs(heroi["vx"])

    # Disparar
    if heroi["recarga"] > 0:
        heroi["recarga"] -= 1
    if heroi["recuo"] > 0:
        heroi["recuo"] -= 1
    if comando["disparar"] and heroi["recarga"] == 0:
        heroi["recarga"] = TEMPO_ENTRE_TIROS
        heroi["recuo"] = 8
        nivel["tiros"].append({
            "x": heroi["x"] + 15 + heroi["virado"] * 18,
            "y": heroi["y"] + 22,
            "vx": VEL_TIRO * heroi["virado"],
            "vida": ALCANCE_TIRO,
        })
        tocar("tiro")
        acao("FOGO!")


def perder_vida(voltar_atras):
    # voltar_atras: True quando se cai num buraco, na lava ou nos espinhos,
    # e o Faisca volta ao ultimo ponto de controlo.
    if jogo["fase"] != "jogar":
        return
    if heroi["invencivel"] > 0 and not voltar_atras:
        return
    if not nivel["treino"]:         # no recreio nao se perdem coracoes
        heroi["vidas"] -= 1
    nivel["sem_falhas"] = False
    jogo["tremor"] = 14
    tocar("pancada")
    particulas(heroi["x"] + 15, heroi["y"] + 20, COR_HEROI, 14, 5)
    if heroi["vidas"] <= 0:
        jogo["fase"] = "perdeu"
        jogo["espera"] = 50
        tocar("perdeu")
        return
    if voltar_atras:
        repor_heroi(nivel["ponto"][0], nivel["ponto"][1])
        heroi["virado"] = 1
    heroi["invencivel"] = 110


def concluir_nivel():
    indice = jogo["indice"]
    estrelas = 1
    if nivel["apanhadas"] == nivel["total_moedas"]:
        estrelas += 1
    if nivel["sem_falhas"]:
        estrelas += 1
    if nivel["treino"]:
        estrelas = 0                # o recreio nao da estrelas nem moedas
    else:
        jogo["moedas"] += nivel["apanhadas"]
    nivel["ganhas"] = estrelas
    if estrelas > jogo["estrelas"].get(indice, 0):
        jogo["estrelas"][indice] = estrelas
    if indice + 1 > jogo["aberto"] and indice + 1 < len(NIVEIS):
        jogo["aberto"] = indice + 1
    jogo["fase"] = "nivel_feito"
    jogo["espera"] = 50
    tocar("vitoria")


def tocar_no_mapa():
    # Tudo aquilo em que o Faisca toca sem ser parede: molas, espinhos,
    # lava, moedas, coracoes, pontos de controlo e a saida.
    eu = retangulo(heroi)

    if heroi["y"] > LINHAS * TILE + 80:
        perder_vida(True)
        return

    coluna_0 = eu.left // TILE
    coluna_1 = (eu.right - 1) // TILE
    linha_0 = eu.top // TILE
    linha_1 = (eu.bottom - 1) // TILE
    for linha in range(linha_0, linha_1 + 1):
        for coluna in range(coluna_0, coluna_1 + 1):
            letra = letra_em(coluna, linha)
            x = coluna * TILE
            y = linha * TILE
            if letra == "M":
                if heroi["vy"] >= 0 and eu.bottom >= y + 20:
                    heroi["vy"] = -FORCA_MOLA
                    heroi["no_chao"] = False
                    heroi["coiote"] = 0
                    tocar("mola")
                    acao("BOING!")
            elif letra == "^":
                if eu.colliderect(pygame.Rect(x + 8, y + 22, TILE - 16, 26)):
                    perder_vida(True)
                    return
            elif letra == "~":
                if eu.colliderect(pygame.Rect(x, y + 14, TILE, TILE - 14)):
                    perder_vida(True)
                    return

    # Pontes podres: comecam a tremer quando se lhes poe os pes em cima.
    if heroi["no_chao"]:
        linha = eu.bottom // TILE
        for coluna in range(coluna_0, coluna_1 + 1):
            if letra_em(coluna, linha) == "%" and (coluna, linha) not in nivel["pontes"]:
                nivel["pontes"][(coluna, linha)] = 28

    restantes = []
    for moeda in nivel["moedas"]:
        if eu.colliderect(moeda):
            nivel["apanhadas"] += 1
            tocar("moeda")
            particulas(moeda.centerx, moeda.centery, COR_MOEDA, 6, 3)
        else:
            restantes.append(moeda)
    nivel["moedas"] = restantes

    restantes = []
    for coracao in nivel["coracoes"]:
        if eu.colliderect(coracao) and heroi["vidas"] < VIDAS:
            heroi["vidas"] += 1
            tocar("moeda")
            particulas(coracao.centerx, coracao.centery, VERMELHO, 10, 3)
        else:
            restantes.append(coracao)
    nivel["coracoes"] = restantes

    for controlo in nivel["controlos"]:
        if not controlo["ativo"] and eu.colliderect(controlo["rect"]):
            controlo["ativo"] = True
            nivel["ponto"] = (controlo["rect"].x - 5, controlo["rect"].bottom - ALTURA_HEROI)
            tocar("controlo")
            particulas(controlo["rect"].centerx, controlo["rect"].top, VERDE, 12, 4)

    if nivel["saida"] is not None and not nivel["trancada"]:
        if eu.colliderect(nivel["saida"]):
            concluir_nivel()



    if passo >= len(TREINO):
        return saltou
    if passo_do_treino_cumprido(passo, m, saltou):
        jogo["treino_espera"] += 1
        # tem de se aguentar o gesto um bocadinho (menos o salto, que e um instante)
        if jogo["treino_espera"] >= 20 or passo == 4:
            jogo["treino_passo"] += 1
            jogo["treino_espera"] = 0
            tocar("controlo")
    else:
        jogo["treino_espera"] = 0
    return False



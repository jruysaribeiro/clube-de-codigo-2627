def ler_comandos(teclas, m, saltou):
    comando = {"direcao": 0, "andar": False, "correr": False,
               "saltar": saltou, "disparar": False}

    if m["visivel"]:
        comando["andar"] = True
        if m["x"] < ZONA_ESQUERDA:
            comando["direcao"] = -1
        elif m["x"] > ZONA_DIREITA:
            comando["direcao"] = 1
        # Para correr ha uma pequena folga, senao a mao mesmo em cima da
        # linha fazia o Faisca correr-nao-correr-correr.
        if m["y"] < LINHA_CORRER:
            jogo["mao_corre"] = True
        elif m["y"] > LINHA_CORRER + 0.06:
            jogo["mao_corre"] = False
        comando["correr"] = jogo["mao_corre"]
        comando["disparar"] = m["forma"] == "apontar"
    else:
        jogo["mao_corre"] = False

    if jogo["modo_teclado"]:
        comando["andar"] = True
    if teclas[pygame.K_LEFT]:
        comando["direcao"] = -1
        comando["andar"] = True
    if teclas[pygame.K_RIGHT]:
        comando["direcao"] = 1
        comando["andar"] = True
    if teclas[pygame.K_DOWN]:
        comando["andar"] = False
    if teclas[pygame.K_LSHIFT] or teclas[pygame.K_RSHIFT]:
        comando["correr"] = True
    if teclas[pygame.K_x] or teclas[pygame.K_z]:
        comando["disparar"] = True
    return comando



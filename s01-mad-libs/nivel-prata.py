print(f"Nesse momento entrou um {animal} pela janela.")
print(f"Fez {som} tres vezes e comeu toda a {comida}.")
print()
print("=== CAPITULO 3: O FIM ===")
print(f"Desde esse dia, {vilao} tem medo de {animal}.")
print(f"E em {lugar} nunca mais se serviu {comida}.")
print(f"{heroi} ficou famoso, e continua a dizer {palavra} a toda a hora.")

heroi = input("Nome do heroi: ")
vilao = input("Nome do vilao: ")
lugar = input("Um lugar da escola: ")
comida = input("A pior comida da cantina: ")
arma = input("Um objeto da sala de aula: ")
animal = input("Um animal: ")
som = input("Um som: ")
palavra = input("Uma palavra que digas muitas vezes: ")

print()
print("=== CAPITULO 1: O AVISO ===")
print(f"{heroi} estava em {lugar} quando ouviu {som}.")
print(f"Era {vilao}, com um tabuleiro de {comida} em cada mao.")
print(f"— {palavra}! — gritou {heroi}, que so dizia isso quando tinha medo.")
print()
print("=== CAPITULO 2: O COMBATE ===")
print(f"{heroi} agarrou {arma} e atirou-o contra {vilao}.")
